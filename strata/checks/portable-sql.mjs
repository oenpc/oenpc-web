/**
 * 约束 id: portable-sql（面：层 D × 全部域）
 *
 * 契约：exit 0 = 通过 / 1 = 失败 / 2 = 无法判定
 *
 * 规则：**SQLite 专有语法必须集中在方言适配层**，不散落到各仓储实现。
 *
 * 为什么这条重要：用户明确要求「预留 PostgreSQL 对接」。
 * 若 SQLite 专有语法散落在几十个仓储文件里，切 PG 时就要逐处改写 ——
 * 那时「预留」只是一句空话。这条约束让「可移植」变成**可机械检查**的性质。
 *
 * 与 `no-sql-in-routes` 的分工：
 *   · `no-sql-in-routes` 管**位置**（SQL 不许出现在 R/C 层）
 *   · `portable-sql` 管**方言**（D 层里的 SQL 不许用 SQLite 专有语法）
 *
 * ## 豁免
 *
 * 方言适配层**必须**用到 SQLite 专有语法（那正是它的职责）。
 * 在该行或上一行写 `// strata-allow-dialect` 即可豁免，且**豁免会被记录** ——
 * 静默豁免会变成垃圾场，而一个开始喊狼来了的约束会被绕过、然后彻底失效。
 */

import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

export const meta = {
  id: 'portable-sql',
  contract: '0=通过 1=失败 2=无法判定',
}

const RULES = [
  {
    id: 'insert-or',
    pattern: /\bINSERT\s+OR\s+(?:REPLACE|IGNORE|ABORT|FAIL|ROLLBACK)\b|\bREPLACE\s+INTO\b/i,
    fix: 'PG 用 INSERT ... ON CONFLICT (<键>) DO UPDATE SET ... / DO NOTHING',
  },
  {
    id: 'autoincrement',
    pattern: /\bAUTOINCREMENT\b/i,
    fix: 'PG 用 GENERATED BY DEFAULT AS IDENTITY（或 SERIAL）',
  },
  {
    id: 'sqlite-time',
    pattern: /\b(?:strftime|julianday)\s*\(|\b(?:datetime|date|time)\s*\(\s*'now'/i,
    fix: '时间由应用层产出 ISO8601 UTC 字符串（见约束 utc-storage），不要交给数据库函数',
  },
  {
    id: 'pragma',
    pattern: /\bPRAGMA\s+\w+/i,
    fix: 'PG 没有 PRAGMA；这类连接级设置应移到驱动/适配层配置',
  },
]

export async function run({ root, targets }) {
  if (!targets || targets.length === 0) {
    return {
      status: 2,
      summary: '没有适用文件（D 层尚未落地），无法判定',
      details: ['索引里没有落在 ⟨D⟩ 面上的条目 —— 约束无处生效。'],
    }
  }

  const violations = []
  const allowed = []
  let unreadable = 0

  for (const relative of targets) {
    let source
    try {
      source = readFileSync(join(root, relative), 'utf8')
    } catch {
      unreadable += 1
      continue
    }

    const lines = source.split('\n')
    lines.forEach((raw, index) => {
      const trimmed = raw.trim()
      if (trimmed.startsWith('//') || trimmed.startsWith('*') || trimmed.startsWith('/*')) return

      /* 豁免：本行或上一行含 strata-allow-dialect */
      const escaped =
        raw.includes('strata-allow-dialect') ||
        (index > 0 && lines[index - 1].includes('strata-allow-dialect'))

      for (const rule of RULES) {
        if (!rule.pattern.test(raw)) continue
        if (escaped) {
          allowed.push({ file: relative, line: index + 1, rule: rule.id, text: trimmed.slice(0, 90) })
        } else {
          violations.push({ file: relative, line: index + 1, rule: rule.id, fix: rule.fix, text: trimmed.slice(0, 100) })
        }
      }
    })
  }

  const details = []

  const allowedNote = allowed.length > 0
    ? [
      '',
      `已豁免 ${allowed.length} 处（所在行或上一行含 strata-allow-dialect）：`,
      ...allowed.map((a) => `  ${a.file}:${a.line}  [${a.rule}]  ${a.text}`),
      '  方言适配层用到 SQLite 专有语法是**正确的** —— 但这些豁免应集中在一处，',
      '  而不是散落在各仓储实现里。',
    ]
    : []

  if (violations.length > 0) {
    details.push(`portable-sql: ${violations.length} 处 SQLite 专有语法`)
    for (const v of violations) {
      details.push(`  ${v.file}:${v.line}  [${v.rule}]  ${v.text}`)
      details.push(`      改法：${v.fix}`)
    }
    details.push('')
    details.push('修法：把方言差异收进一个适配层（如 apps/server/src/db/dialect.*），')
    details.push('      仓储实现只调用适配层导出的能力，不直接写方言语法。')
    details.push('      确属适配层自身的行，加 `// strata-allow-dialect` 豁免。')
    details.push('      另注：参数占位符 `?`（SQLite）与 `$1`（PG）的差异也应由适配层吸收。')
    details.push(...allowedNote)
    return { status: 1, summary: `SQLite 专有语法 ${violations.length} 处`, details }
  }

  if (unreadable > 0) {
    details.push(`有 ${unreadable} 个文件无法读取，判定不完整。`)
    return { status: 2, summary: `${unreadable} 个文件读不了，判定不完整`, details }
  }

  details.push(`检查了 ${targets.length} 个 D 层文件，未发现 SQLite 专有语法散落。`)
  details.push('（文本启发式：参数占位符 ? 与 $1 的差异检测不到，需靠评审。）')
  details.push(...allowedNote)
  return {
    status: 0,
    summary: `通过（${targets.length} 个文件${allowed.length > 0 ? `，豁免 ${allowed.length} 处` : ''}）`,
    details,
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = await run({ root: process.cwd(), targets: process.argv.slice(2) })
  for (const line of result.details ?? []) console.error(line)
  console.log(`${meta.id}: ${result.summary}`)
  process.exit(result.status)
}
